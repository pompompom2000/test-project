const inquiry = (no, title, note, fact, mine, base, ask, first) => {
  const out = [];
  out.push(p(`【${no}】　${title}`, { go: true, bold: true, size: 24, before: first ? 0 : 400, after: 140, br: !first }));
  if (note) out.push(...note.map((t) => p(t, { size: 17, line: 250 })), p("", { after: 60 }));
  out.push(band("１　前提とする事実"));
  out.push(...fact.map((t) => p(t, { line: 290, indent: { left: 180 } })));
  out.push(p("", { after: 80 }));
  out.push(band("２　当社の理解"));
  out.push(...mine.map((t) => p(t, { line: 290, indent: { left: 180 } })));
  out.push(p("", { after: 80 }));
  out.push(band("３　根拠にしている資料"));
  out.push(...base.map((t) => p(t, { line: 290, indent: { left: 180 }, size: 19 })));
  out.push(p("", { after: 80 }));
  out.push(band("４　お聞きしたいこと"));
  out.push(...ask.map((t) => p(t, { line: 290, indent: { left: 180 } })));
  out.push(p("", { after: 120 }));
  out.push(mk([W], [new TableRow({ children: [cell([
    "【回答欄】　※ご記入いただくか、口頭でお聞かせください。当社で記録いたします。", "", "", "", "", "",
  ], W, { top: true, size: 18 })] })]));
  return out;
};

