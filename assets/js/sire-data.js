/** "サートゥルナーリア(牡)" → { name: 'サートゥルナーリア', sex: '牡' } */
function parseSireEntry(entry) {
  const m = entry.match(/^(.+?)\((牡|牝)\)$/);
  return m ? { name: m[1], sex: m[2] } : { name: entry, sex: null };
}

