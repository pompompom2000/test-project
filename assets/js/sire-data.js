/**
 * JRA-VAN 記事（2020〜2022年・芝）で挙げられていた道悪巧者／不振の種牡馬。
 * [1][2] より古い集計なので、補助シグナルとして小さめの重みで使う。
 * 出典: https://jra-van.jp/fun/baken/index23.html
 */
const LEGACY_TURF_SIRES = {
  strong: ['オルフェーヴル', 'ゴールドシップ', 'キングズベスト'],
  good: ['キタサンブラック'],
  weak: ['エピファネイア', 'ジャスタウェイ'],
};

const LEGACY_WEIGHTS = { strong: 6, good: 4, weak: -6 };

/** 補助シグナル（芝のみ）。該当しなければ null。 */
function legacyTurfHit(surfaceKey, sireName) {
  if (surfaceKey !== 'turf' || !sireName) return null;
  for (const [tier, names] of Object.entries(LEGACY_TURF_SIRES)) {
    if (names.includes(sireName)) return { tier, value: LEGACY_WEIGHTS[tier] };
  }
  return null;
}

/** 加点・減点の重み。 */
const SIRE_WEIGHTS = {
  favorable: 16,
  unfavorable: -14,
  watch: 9,
  poor: -9,
  pick2026: 5,
};

/** 性別指定つきエントリに馬の性別が一致するか。指定なしは常に一致。 */
function sexMatches(entrySex, horseSex) {
  if (!entrySex) return true;
  if (!horseSex) return false; // 性別未入力なら性別限定の傾向は適用しない
  return entrySex === horseSex;
}

function listHit(list, sireName, horseSex) {
  if (!sireName) return null;
  for (const raw of list) {
    const entry = parseSireEntry(raw);
    if (entry.name === sireName && sexMatches(entry.sex, horseSex)) return entry;
  }
  return null;
}

/** オートコンプリート用に、データに登場する全種牡馬名を重複なしで返す。 */
function allSireNames() {
  const names = new Set();
  for (const surface of Object.values(SIRE_DB)) {
    const lists = [
      surface.favorable,
      surface.unfavorable,
      surface.picks2026,
      ...Object.values(surface.watch),
      ...Object.values(surface.poor),
    ];
    lists.forEach((list) => list.forEach((raw) => names.add(parseSireEntry(raw).name)));
  }
  return [...names].sort();
}
